--- Checks the header of an exchange file. Returns nil, reason when it cannot be imported.
function Exchange.CheckHeader(exchange, schema, now)
	if type(exchange) ~= "table" or next(exchange) == nil then
		return nil, "empty"
	end
	if exchange.kind ~= ns.EXCHANGE_KIND then
		return nil, "This file is not a TRP3 Directory Keeper export."
	end
	if exchange.format ~= ns.EXCHANGE_FORMAT then
		return nil, ("This export uses file format %s, but this version of TRP3 Directory Keeper reads format %s. Update the addon on both sides."):format(tostring(exchange.format), ns.EXCHANGE_FORMAT)
	end
	if exchange.schema ~= schema then
		return nil, ("This export was made with Total RP 3 data format %s, but your Total RP 3 uses %s. Both players need the same Total RP 3 version."):format(tostring(exchange.schema), tostring(schema))
	end
	if type(exchange.exportedAt) ~= "number" or exchange.exportedAt > now + 86400 then
		return nil, "This export has an invalid date (is the exporter's PC clock wrong?)."
	end
	for _, section in ipairs(ns.SECTIONS) do
		if type(exchange[section]) ~= "table" then
			return nil, "This export is damaged."
		end
	end
	return true
end

--- Reads an exchange file and works out what an import would add. Runs inside a job.
--- Nothing is changed here; Exchange.Apply does that after the player confirms.
function Exchange.Plan(exchange, directory, blockList, sanitize)
	blockList = type(blockList) == "table" and blockList or {}
	local exportedAt = exchange.exportedAt

	local incoming = {}
	for _, section in ipairs(ns.SECTIONS) do
		local entries = {}
		for _, chunk in ipairs(exchange[section]) do
			for key, value in pairs(Serializer.Parse(chunk)) do
				entries[key] = value
			end
			ns.MaybeYield()
		end
		incoming[section] = entries
	end

	local plan = { profiles = {}, characters = {}, companions = {} }
	local report = {
		exportedAt = exportedAt, newCharacters = 0, newProfiles = 0, linkedToKnownProfile = 0, newCompanions = 0,
		knownCharacters = 0, ignored = 0, invalid = 0, knownCompanions = 0,
	}
	local rejected = {}

	local steps = 0
	for characterID, entry in pairs(incoming.character) do
		local character = IsValidID(characterID) and Exchange.CleanCharacter(entry)
		if not character then
			report.invalid = report.invalid + 1
		elseif blockList[characterID] then
			report.ignored = report.ignored + 1
		elseif directory.character[characterID] ~= nil then
			report.knownCharacters = report.knownCharacters + 1
		else
			local profileID = character.profileID
			if directory.profiles[profileID] ~= nil then
				plan.characters[characterID] = character
				report.linkedToKnownProfile = report.linkedToKnownProfile + 1
			else
				local profile = plan.profiles[profileID]
				if profile == nil and not rejected[profileID] then
					profile = Exchange.CleanProfile(profileID, incoming.profiles[profileID], exportedAt, sanitize)
					if profile then
						plan.profiles[profileID] = profile
						report.newProfiles = report.newProfiles + 1
					else
						rejected[profileID] = true
					end
				end
				if profile then
					profile.link[characterID] = 1
					plan.characters[characterID] = character
				else
					report.invalid = report.invalid + 1
				end
			end
		end
		steps = steps + 1
		if steps % 200 == 0 then ns.MaybeYield() end
	end
	report.newCharacters = ns.CountKeys(plan.characters)

	-- Companions: add new ones, linked only to owners that are (or will be) in the directory, and only
	-- for pets and mounts that do not already have a companion profile.
	local boundCompanions = {}
	for _, companion in pairs(directory.companion or {}) do
		if type(companion) == "table" and type(companion.links) == "table" then
			for companionFullID in pairs(companion.links) do boundCompanions[companionFullID] = true end
		end
	end
	for companionID, entry in pairs(incoming.companion) do
		if directory.companion and directory.companion[companionID] ~= nil then
			report.knownCompanions = report.knownCompanions + 1
		else
			local companion = IsValidProfileID(companionID) and Exchange.CleanCompanion(entry)
			if companion then
				local links = {}
				for companionFullID in pairs(companion.links) do
					local owner = Archive.CompanionOwner(companionFullID)
					if owner and not boundCompanions[companionFullID] and not blockList[owner]
						and (directory.character[owner] or plan.characters[owner]) then
						links[companionFullID] = 1
						boundCompanions[companionFullID] = true
					end
				end
				if next(links) then
					companion.links = links
					plan.companions[companionID] = companion
					report.newCompanions = report.newCompanions + 1
				end
			else
				report.invalid = report.invalid + 1
			end
		end
		steps = steps + 1
		if steps % 200 == 0 then ns.MaybeYield() end
	end

	return plan, report
end

--- Adds a planned import to TRP3's directory and the archive. Imported entries are marked as
--- archive entries, so they are not saved into TRP3's own file at logout.
function Exchange.Apply(plan, directory, archive, session)
	local profiles, characters = directory.profiles, directory.character
	directory.companion = directory.companion or {}
	local added = { profiles = 0, characters = 0, companions = 0 }

	for profileID, profile in pairs(plan.profiles) do
		if profiles[profileID] == nil then
			profile.link = {}
			profiles[profileID] = profile
			archive.profiles[profileID] = profile
			session.injectedProfiles[profileID] = true
			session.importedProfiles[profileID] = true
			added.profiles = added.profiles + 1
		end
	end
	for characterID, character in pairs(plan.characters) do
		local profile = profiles[character.profileID]
		if characters[characterID] == nil and profile then
			characters[characterID] = character
			archive.character[characterID] = character
			session.injectedCharacters[characterID] = true
			if type(profile.link) ~= "table" then profile.link = {} end
			profile.link[characterID] = 1
			added.characters = added.characters + 1
		end
	end
	for companionID, companion in pairs(plan.companions) do
		if directory.companion[companionID] == nil then
			directory.companion[companionID] = companion
			archive.companion[companionID] = companion
			session.injectedCompanions[companionID] = true
			added.companions = added.companions + 1
		end
	end
	return added
end

---------------------------------------------------------------------------
-- In-game flows (buttons and /tdk commands)
---------------------------------------------------------------------------

local function GetSchema()
	return TRP3_Flyway and TRP3_Flyway.currentBuild
end

local function GetTRP3Version()
	return C_AddOns.GetAddOnMetadata("totalRP3", "Version") or "?"
end

--- Loads the exchange slot addon. Returns true, or false after telling the player why not.
local function LoadExchangeSlot()
	if C_AddOns.IsAddOnLoaded(ns.EXCHANGE_ADDON) then return true end
	local loaded, reason = C_AddOns.LoadAddOn(ns.EXCHANGE_ADDON)
	if not loaded then
		ns.UI.Alert(("The addon \"TRP3 Directory Keeper: Exchange\" could not be loaded (%s). Enable it in the AddOns list, then try again."):format(tostring(reason)))
		return false
	end
	return true
end

-- The game does not tell addons where it is installed or what the account folder is called, so the
-- path is shown with a placeholder (red) and the file name (green), split over lines to fit the popup.
local FILE_PATH = "World of Warcraft\\_retail_\\WTF\\Account\\\n"
	.. "|cffff2020<YOUR ACCOUNT FOLDER>|r\\SavedVariables\\\n"
	.. "|cff20ff20TRP3_DirectoryKeeper_Exchange.lua|r"
local FOLDER_HINT = "|cff66ccffTo open your World of Warcraft folder: in the Battle.net app, select World of Warcraft, "
	.. "click the gear icon next to the Play button, then Show in Explorer. Most players have exactly one folder inside WTF\\Account.|r"

function Exchange.StartExport()
	local directory = TRP3_Register
	if type(directory) ~= "table" or type(directory.profiles) ~= "table" then
		ns.UI.Alert("Total RP 3's directory is not available.")
		return
	end
	if not LoadExchangeSlot() then return end

	local selection = Exchange.SelectExport(directory, directory.blockList)
	local text = ("Export your directory?\n\n%d characters, %d profiles and %d companions. Your ignore list and anything belonging to ignored characters are not included.")
		:format(#selection.characterIDs, #selection.profileIDs, #selection.companionIDs)
	local existing = _G[ns.EXCHANGE_VARIABLE]
	if type(existing) == "table" and existing.kind == ns.EXCHANGE_KIND then
		text = text .. ("\n\nThis replaces the export currently in the exchange file (from %s)."):format(ns.FormatDate(existing.exportedAt))
	end

	ns.UI.Confirm(text, function()
		local started = debugprofilestop()
		ns.Print("Exporting the directory...")
		ns.RunJob("export", function()
			return Exchange.BuildExport(directory, directory.blockList, {
				trp3Version = GetTRP3Version(), schema = GetSchema(), now = time(),
			})
		end, function(ok, export)
			if not ok then
				ns.UI.Alert("The export failed: " .. tostring(export))
				return
			end
			_G[ns.EXCHANGE_VARIABLE] = export
			local c = export.counts
			ns.Print("Export ready in %.1f s: %d characters, %d profiles, %d companions.",
				(debugprofilestop() - started) / 1000, c.characters, c.profiles, c.companions)
			ns.UI.ConfirmReload(("Export ready: %d characters, %d profiles, %d companions.\n\nThe game saves the file when you reload or log out. You will find it here:\n\n%s\n\n%s\n\nReload now?")
				:format(c.characters, c.profiles, c.companions, FILE_PATH, FOLDER_HINT))
		end)
	end)
end

local ReadImport

--- Asks first whether the received file is in place, with the same directions as after an export.
function Exchange.StartImport()
	local session = ns.session
	if not session or not session.complete then
		ns.UI.Alert("Importing is unavailable right now: " .. (ns.status.pauseReason or "the archive is not active") .. ".")
		return
	end
	ns.UI.AskImportReady(("Import a received directory?\n\nFor the import to work, the file needs to be placed in:\n\n%s\n\nPut it there while the game is closed, or at the character selection screen. Overwrite if a file with the same name is present already.\n\n%s")
		:format(FILE_PATH, FOLDER_HINT), ReadImport)
end

function ReadImport()
	if not LoadExchangeSlot() then return end

	local exchange = _G[ns.EXCHANGE_VARIABLE]
	local ok, reason = Exchange.CheckHeader(exchange, GetSchema(), time())
	if not ok then
		if reason == "empty" then
			reason = ("No export file found.\n\n1. Close the game, or go to the character selection screen.\n\n2. Put the received file here, replacing any file with the same name:\n\n%s\n\n3. Log in, open the Directory and click Import.\n\n%s")
				:format(FILE_PATH, FOLDER_HINT)
		end
		ns.UI.Alert(reason)
		return
	end

	local sanitize
	if TRP3_API and TRP3_API.register and TRP3_API.register.sanitizeProfile then
		local sanitizeProfile = TRP3_API.register.sanitizeProfile
		sanitize = function(profileID, profile)
			for _, infoType in ipairs({ "characteristics", "character", "misc" }) do
				if type(profile[infoType]) == "table" then
					sanitizeProfile(infoType, profileID, profile[infoType])
				end
			end
		end
	end

	ns.Print("Reading the export from %s...", ns.FormatDate(exchange.exportedAt))
	local directory = TRP3_Register
	ns.RunJob("import", function()
		return Exchange.Plan(exchange, directory, directory.blockList, sanitize)
	end, function(planned, plan, report)
		if not planned then
			ns.UI.Alert("This export could not be read: " .. tostring(plan))
			return
		end
		local text = ("Import the export from %s?\n\nWill add: %d characters (%d new profiles, %d linked to profiles you already have) and %d companions.\n\nSkipped: %d characters you already have, %d ignored, %d invalid entries.\n\nThe game reloads after the import.")
			:format(ns.FormatDate(report.exportedAt), report.newCharacters, report.newProfiles, report.linkedToKnownProfile,
				report.newCompanions, report.knownCharacters, report.ignored, report.invalid)
		if report.newCharacters == 0 and report.newCompanions == 0 then
			ns.UI.Alert(("Nothing to import: everything in the export from %s is already in your directory (%d characters known, %d ignored, %d invalid).")
				:format(ns.FormatDate(report.exportedAt), report.knownCharacters, report.ignored, report.invalid))
			return
		end
		ns.UI.ConfirmImport(text, function()
			local added = Exchange.Apply(plan, TRP3_Register, ns.archive, ns.session)
			ns.Print("Imported %d profiles, %d characters and %d companions. Reloading...", added.profiles, added.characters, added.companions)
			ReloadUI()
		end)
	end)
end
