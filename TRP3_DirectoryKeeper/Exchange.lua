-- Export
---------------------------------------------------------------------------

--- Chooses what an export contains: every character that is not ignored and has a profile, the
--- profiles those characters use, and the companions of those characters. Profiles no character
--- points to (TRP3 keeps them after a player switches profiles, but never lists them) are left out.
function Exchange.SelectExport(directory, blockList)
	blockList = type(blockList) == "table" and blockList or {}
	local profiles, characters, companions = directory.profiles, directory.character, directory.companion

	local exportedCharacters, characterIDs = {}, {}
	for characterID, character in pairs(characters) do
		if type(character) == "table" and character.profileID and profiles[character.profileID]
			and not blockList[characterID] and IsValidID(characterID) then
			exportedCharacters[characterID] = true
			characterIDs[#characterIDs + 1] = characterID
		end
	end
	local profileIDs, exportedProfiles = {}, {}
	for _, characterID in ipairs(characterIDs) do
		local profileID = characters[characterID].profileID
		if not exportedProfiles[profileID] then
			exportedProfiles[profileID] = true
			profileIDs[#profileIDs + 1] = profileID
		end
	end
	local companionIDs = {}
	for companionID, companion in pairs(companions or {}) do
		if type(companion) == "table" and type(companion.links) == "table" then
			for companionFullID in pairs(companion.links) do
				if exportedCharacters[Archive.CompanionOwner(companionFullID) or ""] then
					companionIDs[#companionIDs + 1] = companionID
					break
				end
			end
		end
	end
	return {
		characterIDs = characterIDs, profileIDs = profileIDs, companionIDs = companionIDs,
		exportedCharacters = exportedCharacters,
	}
end

--- Builds the export of a directory. Runs inside a job (calls ns.MaybeYield).
--- The selection is made first because TRP3 can change the directory while the export runs.
function Exchange.BuildExport(directory, blockList, info)
	local profiles, characters, companions = directory.profiles, directory.character, directory.companion
	local selection = Exchange.SelectExport(directory, blockList)
	local characterIDs, profileIDs, companionIDs = selection.characterIDs, selection.profileIDs, selection.companionIDs
	local exportedCharacters = selection.exportedCharacters
	ns.MaybeYield()

	local function FilteredLinks(links)
		local result = {}
		for id in pairs(links or {}) do
			local owner = Archive.CompanionOwner(id) or id
			if exportedCharacters[id] or exportedCharacters[owner] then result[id] = 1 end
		end
		return result
	end

	local counts = { profiles = 0, characters = 0, companions = 0 }

	local chunker = Serializer.NewChunker()
	for _, profileID in ipairs(profileIDs) do
		local profile = profiles[profileID]
		if type(profile) == "table" then
			local copy = {}
			for key, value in pairs(profile) do copy[key] = value end
			copy.link = FilteredLinks(profile.link)
			if chunker:Add(profileID, copy) then counts.profiles = counts.profiles + 1 end
		end
		ns.MaybeYield()
	end
	local profileChunks = chunker:Finish()

	chunker = Serializer.NewChunker()
	for _, characterID in ipairs(characterIDs) do
		local character = characters[characterID]
		if type(character) == "table" then
			if chunker:Add(characterID, character) then counts.characters = counts.characters + 1 end
		end
		ns.MaybeYield()
	end
	local characterChunks = chunker:Finish()

	chunker = Serializer.NewChunker()
	for _, companionID in ipairs(companionIDs) do
		local companion = companions[companionID]
		if type(companion) == "table" then
			local copy = {}
			for key, value in pairs(companion) do copy[key] = value end
			copy.links = FilteredLinks(companion.links)
			if chunker:Add(companionID, copy) then counts.companions = counts.companions + 1 end
		end
		ns.MaybeYield()
	end
	local companionChunks = chunker:Finish()

	return {
		kind = ns.EXCHANGE_KIND,
		format = ns.EXCHANGE_FORMAT,
		addonVersion = ns.VERSION,
		trp3Version = info.trp3Version,
		schema = info.schema,
		exportedAt = info.now,
		counts = counts,
		profiles = profileChunks,
		character = characterChunks,
		companion = companionChunks,
	}
end

