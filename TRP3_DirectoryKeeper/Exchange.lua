-- TRP3 Directory Keeper
-- Exporting the directory to a file and importing someone else's.
--
-- The file people exchange is the saved-variables file of the load-on-demand addon
-- TRP3_DirectoryKeeper_Exchange (WTF\Account\<account>\SavedVariables\TRP3_DirectoryKeeper_Exchange.lua).
-- That addon is only loaded when Export or Import is used, so the game never overwrites a received
-- file just because you played.
--
-- Export: everything shown in TRP3's directory, except the ignore list and anything belonging to
--         ignored characters, serialized into chunk strings. The game writes the file at the next
--         reload or logout.
-- Import: adds only what is new (add-only). Characters already in the directory are skipped,
--         ignored characters are skipped, and new characters of an already known profile are linked
--         to your copy of it. Every entry is validated and passed through TRP3's own sanitizers.
--         Imported entries go into the archive; TRP3's own file is not enlarged by an import.

local _, ns = ...

local Serializer, Archive = ns.Serializer, ns.Archive
local pairs, ipairs, next, type, pcall = pairs, ipairs, next, type, pcall
local find = string.find

local Exchange = {}
ns.Exchange = Exchange

---------------------------------------------------------------------------
-- Background jobs: long work is split over frames so the game keeps running
---------------------------------------------------------------------------

local FRAME_BUDGET_MS = 15
local job, jobFrame

function ns.RunJob(label, fn, onFinished)
	if job then
		ns.Print("Please wait, the %s is still running.", job.label)
		return false
	end
	jobFrame = jobFrame or CreateFrame("Frame")
	job = { label = label, co = coroutine.create(fn), deadline = 0 }
	jobFrame:SetScript("OnUpdate", function()
		job.deadline = debugprofilestop() + FRAME_BUDGET_MS
		local ok, result, extra = coroutine.resume(job.co)
		if not ok or coroutine.status(job.co) == "dead" then
			jobFrame:SetScript("OnUpdate", nil)
			job = nil
			onFinished(ok, result, extra)
		end
	end)
	return true
end

--- Called often inside jobs; gives the frame back to the game when this frame's budget is used up.
--- Never call it from inside pcall (Lua 5.1 cannot yield across pcall).
function ns.MaybeYield()
	if job and coroutine.running() == job.co and debugprofilestop() > job.deadline then
		coroutine.yield()
	end
end

---------------------------------------------------------------------------
-- Validation of received entries
---------------------------------------------------------------------------

local MAX_ID_BYTES = 128
local MAX_TEXT_BYTES = 256 * 1024 -- longest text seen in a real directory: 108 KB (an About page)
local MAX_TREE_DEPTH = 10
local MAX_TREE_NODES = 20000

local PROFILE_FIELDS = {
	characteristics = "table", about = "table", misc = "table", character = "table",
	link = "table", mspver = "table", time = "number", zone = "string", msp = "boolean",
}
local CHARACTER_FIELDS = {
	profileID = "string", client = "string", clientVersion = "string", extendedVersion = "string",
	msp = "boolean", extended = "number", isTrial = "number", roleplayExperience = "number",
	classID = "number", class = "string", race = "string", gender = "number", faction = "string", guild = "string",
}
local COMPANION_FIELDS = { data = "table", PE = "table", links = "table" }

--- Character IDs ("Name-Realm"): WoW names never contain "|", which would start a UI escape code.
local function IsValidID(id)
	return type(id) == "string" and #id > 0 and #id <= MAX_ID_BYTES and not find(id, "[%c|]")
end
Exchange.IsValidID = IsValidID

--- Profile IDs: generated by TRP3; older versions used symbols too (e.g. "1026160645|p;MP"),
--- so only control characters are refused.
local function IsValidProfileID(id)
	return type(id) == "string" and #id > 0 and #id <= MAX_ID_BYTES and not find(id, "%c")
end
Exchange.IsValidProfileID = IsValidProfileID

-- Plain data only: string or number keys; string, number, boolean or table values; bounded size.
local function IsPlainTree(t, depth, budget)
	if depth > MAX_TREE_DEPTH then return false end
	for key, value in pairs(t) do
		budget.nodes = budget.nodes + 1
		if budget.nodes > MAX_TREE_NODES then return false end
		local keyType, valueType = type(key), type(value)
		if keyType ~= "string" and keyType ~= "number" then return false end
		if keyType == "string" and #key > MAX_TEXT_BYTES then return false end
		if valueType == "string" then
			if #value > MAX_TEXT_BYTES then return false end
		elseif valueType == "table" then
			if not IsPlainTree(value, depth + 1, budget) then return false end
		elseif valueType ~= "number" and valueType ~= "boolean" then
			return false
		end
	end
	return true
end

-- Keeps only known fields of the expected type; returns nil when the entry is not plain data.
local function CleanFields(entry, fields)
	if type(entry) ~= "table" then return nil end
	local clean = {}
	for field, expected in pairs(fields) do
		local value = entry[field]
		if type(value) == expected then
			if expected == "string" and #value > MAX_TEXT_BYTES then return nil end
			clean[field] = value
		end
	end
	if not IsPlainTree(clean, 1, { nodes = 0 }) then return nil end
	return clean
end

function Exchange.CleanCharacter(entry)
	local clean = CleanFields(entry, CHARACTER_FIELDS)
	if clean and IsValidProfileID(clean.profileID) then return clean end
	return nil
end

--- Cleans a received profile. exportedAt caps the last-seen date, so a wrong clock on the
--- exporter's PC cannot make an imported profile look newer than it is.
function Exchange.CleanProfile(profileID, entry, exportedAt, sanitize)
	local clean = CleanFields(entry, PROFILE_FIELDS)
	if not clean or not clean.characteristics or next(clean.characteristics) == nil then return nil end
	if not clean.time or clean.time > exportedAt then clean.time = exportedAt end
	clean.link = {}
	if sanitize and not pcall(sanitize, profileID, clean) then return nil end
	return clean
end

function Exchange.CleanCompanion(entry)
	local clean = CleanFields(entry, COMPANION_FIELDS)
	if not clean or not clean.links or not clean.data then return nil end
	return clean
end

